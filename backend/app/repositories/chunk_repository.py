from __future__ import annotations

import uuid
from collections.abc import Sequence

from sqlalchemy import func, insert, literal_column, select
from sqlalchemy.orm import Session

from app.models.document_model import TSV_CONFIG, Chunk, Document, Section
from app.repositories.interfaces.i_chunk_repository import IChunkRepository
from app.repositories.section_repository import SECTION_COLUMNS


def _with_section(stmt):
    return stmt.select_from(Chunk).join(Section, Section.id == Chunk.section_id).join(
        Document, Document.id == Chunk.document_id
    )


class ChunkRepository(IChunkRepository):
    def __init__(self, session: Session) -> None:
        self.session = session

    def bulk_insert(self, rows: list[dict]) -> None:
        # tsv is generated by PostgreSQL from content
        if rows:
            self.session.execute(insert(Chunk), rows)

    def vector_search(self, query_vec: Sequence[float], document_ids: list[uuid.UUID] | None, k: int) -> list[dict]:
        distance = Chunk.embedding.cosine_distance(query_vec)
        stmt = (
            _with_section(select(Chunk.id.label("chunk_id"), Chunk.content, *SECTION_COLUMNS, (1 - distance).label("score")))
            .where(Document.status == "ready")
            .order_by(distance)
            .limit(k)
        )
        if document_ids:
            stmt = stmt.where(Chunk.document_id.in_(document_ids))
        return [dict(row) for row in self.session.execute(stmt).mappings()]

    def keyword_search(self, terms: list[str], document_ids: list[uuid.UUID] | None, k: int) -> list[dict]:
        if not terms:
            return []
        query = func.to_tsquery(literal_column(f"'{TSV_CONFIG}'"), " | ".join(terms))
        score = func.ts_rank_cd(Chunk.tsv, query)
        stmt = (
            _with_section(select(Chunk.id.label("chunk_id"), Chunk.content, *SECTION_COLUMNS, score.label("score")))
            .where(Document.status == "ready", Chunk.tsv.op("@@")(query))
            .order_by(score.desc())
            .limit(k)
        )
        if document_ids:
            stmt = stmt.where(Chunk.document_id.in_(document_ids))
        return [dict(row) for row in self.session.execute(stmt).mappings()]

    def rows_for_audit(self, document_id: uuid.UUID) -> list[dict]:
        rows = self.session.execute(
            select(Chunk.id, Chunk.content, Chunk.embedding, Section.full_md, Section.path, Section.kind)
            .join(Section, Section.id == Chunk.section_id)
            .where(Chunk.document_id == document_id)
        )
        return [dict(row) for row in rows.mappings()]

    def nearest_section_ids(self, document_id: uuid.UUID, query_vec: Sequence[float], k: int) -> list[uuid.UUID]:
        return list(
            self.session.scalars(
                select(Chunk.section_id)
                .where(Chunk.document_id == document_id)
                .order_by(Chunk.embedding.cosine_distance(query_vec))
                .limit(k)
            ).all()
        )
